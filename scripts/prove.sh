#!/usr/bin/env bash
# make prove (LANE 2): boot a FRESH control plane from clean, run the deferred proving suite against
# the real system (live Postgres + real Docker rooms), capture evidence, tear down deterministically.
# A green here — reproducible from clean — is the trust bar (docs/THOR-TEST-ENVIRONMENT.md).
set -uo pipefail
cd "$(dirname "$0")/.."
PY=.venv/bin/python
REPORT=docs/TEST-REPORT.md
mkdir -p .thor

echo "==================== make prove — fresh-state proof lane ===================="

# Own the plane lifecycle: stop any stray plane, then clean to genesis + reap rooms.
pkill -f tools/start_thor.py 2>/dev/null || true
sleep 1
bash scripts/clean.sh

ROOMS_BEFORE=$(docker ps -a --filter label=thor.room=1 --format '{{.Names}}' | tr '\n' ' ')
echo "docker THOR rooms BEFORE: [${ROOMS_BEFORE}]"

echo "-- booting a fresh control plane --"
$PY tools/start_thor.py > .thor/prove-plane.log 2>&1 &
PLANE_PID=$!

UP=0
for i in $(seq 1 60); do
  if curl -s -m1 http://127.0.0.1:7100/health >/dev/null 2>&1; then UP=1; break; fi
  sleep 1
done
if [ "$UP" != "1" ]; then
  echo "FATAL: control plane did not boot"; cat .thor/prove-plane.log
  kill "$PLANE_PID" 2>/dev/null || true; exit 1
fi

SURF=""
for p in 7100 7080 7140 7150; do
  H=$(curl -s -m2 http://127.0.0.1:$p/health 2>/dev/null || curl -s -m2 -o /dev/null -w "HTTP %{http_code}" http://127.0.0.1:$p/ 2>/dev/null)
  echo "  surface :$p -> $H"
  SURF="${SURF}- \`:$p\` → ${H}\n"
done

echo "-- running the deferred proving suite (pytest -m deferred) --"
$PY -m pytest -m deferred -v --no-header -p no:cacheprovider 2>&1 | tee .thor/prove-pytest.log
RC=${PIPESTATUS[0]}
SUMMARY=$(tail -1 .thor/prove-pytest.log)

ROOMS_AFTER=$(docker ps -a --filter label=thor.room=1 --format '{{.Names}}' | tr '\n' ' ')
echo "docker THOR rooms AFTER suite: [${ROOMS_AFTER}]"

echo "-- teardown: stop plane + reap --"
kill "$PLANE_PID" 2>/dev/null || true
sleep 1
pkill -f tools/start_thor.py 2>/dev/null || true
bash scripts/clean.sh >/dev/null 2>&1 || true
ROOMS_END=$(docker ps -a --filter label=thor.room=1 --format '{{.Names}}' | tr '\n' ' ')

# ---- evidence capture (R6) ----
{
  echo "# THOR — TEST REPORT (generated by make prove)"
  echo ""
  echo "Generated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
  echo ""
  echo "## Result"
  echo ""
  echo "- pytest (LANE 2, \`-m deferred\`): **${SUMMARY}**  (exit ${RC})"
  echo "- THOR rooms before: \`[${ROOMS_BEFORE}]\`  (clean start = empty)"
  echo "- THOR rooms after suite: \`[${ROOMS_AFTER}]\`"
  echo "- THOR rooms after teardown: \`[${ROOMS_END}]\`  (deterministic teardown = empty)"
  echo ""
  echo "## Fresh control plane (booted from clean)"
  echo ""
  echo -e "${SURF}"
  echo "## Suite tail"
  echo ""
  echo '```'
  tail -25 .thor/prove-pytest.log
  echo '```'
} > "$REPORT"
echo "evidence written -> $REPORT"

echo "==================== make prove complete (rc=$RC) ===================="
exit "$RC"
